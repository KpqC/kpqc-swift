FileUtils.rm_rf(OUTPUT)

algorithms.each do |entry|
  directory = File.join(OUTPUT, entry[:name])
  FileUtils.mkdir_p(directory)

  guard = "KPQC_GENERATED_#{entry[:name].upcase}_CONFIG_H"
  definitions = {
    "KPQC_PREFIX" => "kpqc_#{entry[:name]}_",
    "randombytes" => "kpqc_#{entry[:name]}_randombytes"
  }.merge(entry[:defines])
  entry[:renames].each do |symbol|
    definitions[symbol] = "kpqc_#{entry[:name]}_#{symbol}"
  end

  config = ["/* Generated by scripts/generate_native_sources.rb. */",
            "#ifndef #{guard}", "#define #{guard}"]
  definitions.each { |key, value| config << "#define #{key} #{value}" }
  config << "#endif"
  File.write(File.join(directory, "config.h"), config.join("\n") + "\n")

  units = entry[:sources] + ["native/csrc/#{entry[:wrapper]}"]
  units.each_with_index do |source, index|
    basename = File.basename(source, ".c").tr("-+", "__")
    filename = format("%02d_%s.c", index, basename)
    content = File.read(File.join(ROOT, source)).gsub(
      /^(\s*#\s*include\s*)"([^"]+)"/
    ) do
      prefix = Regexp.last_match(1)
      header = Regexp.last_match(2)
      search = [File.dirname(source), *entry[:includes]]
      resolved = search
                 .map { |directory_name| File.join(directory_name, header) }
                 .find { |candidate| File.file?(File.join(ROOT, candidate)) }
      resolved ? "#{prefix}\"#{resolved}\"" : Regexp.last_match(0)
    end
    File.write(
      File.join(directory, filename),
      "/* Generated by scripts/generate_native_sources.rb. */\n" \
      "#include \"config.h\"\n" \
      "#line 1 \"#{source}\"\n" \
      "#{content}"
    )
  end

  File.write(
    File.join(directory, format("%02d_randombytes.c", units.length)),
    "/* Generated by scripts/generate_native_sources.rb. */\n" \
    "#include \"config.h\"\n" \
    "#if defined(KPQC_TEST_ENTROPY)\n" \
    "#include \"native/csrc/randombytes_test.c\"\n" \
    "#else\n" \
    "#include \"native/csrc/randombytes.c\"\n" \
    "#endif\n"
  )
end

