def algorithm(name:, wrapper:, sources:, includes:, defines: {}, renames: [])
  {
    name: name,
    wrapper: wrapper,
    sources: sources,
    includes: includes,
    defines: defines,
    renames: renames
  }
end

algorithms = []

%w[128f 128s 192f 192s 256f 256s].each do |parameter|
  root = "vendor/AIMer"
  name = "aimer#{parameter}"
  algorithms << algorithm(
    name: name,
    wrapper: "signature.c",
    sources: %W[
      #{root}/aim2.c #{root}/hash.c #{root}/sign.c #{root}/tree.c
      #{root}/field#{parameter[0, 3]}.c #{root}/common/fips202.c
    ],
    includes: [root, "#{root}/common"],
    defines: { "PARAMS" => parameter, "KPQC_AIMER" => "1" },
    renames: %w[
      crypto_sign_keypair_internal crypto_sign_signature_internal
      crypto_sign_verify_internal
    ] + PQC_FIPS202_SYMBOLS
  )
end

{ "haetae2" => 0, "haetae3" => 1, "haetae5" => 2 }.each do |name, mode|
  algorithms << algorithm(
    name: name,
    wrapper: "signature.c",
    sources: HAETAE_SOURCES,
    includes: ["vendor/HAETAE/include"],
    defines: { "HAETAE_CONFIG_MODE" => mode.to_s },
    renames: COMPACT_FIPS202_SYMBOLS + HAETAE_SYMBOLS
